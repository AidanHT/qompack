func TestRenderModWire_CarriesEveryConstEnumAndMessage(t *testing.T) {
	src, err := renderModWire()
	require.NoError(t, err)
	s := string(src)

	require.True(t, strings.HasPrefix(s, "// Code generated by `go run ./tools/devtool gen-mod-wire`"))
	schema := modwire.Schema()
	for _, c := range schema.Consts {
		switch v := c.Value.(type) {
		case string:
			require.Contains(t, s, fmt.Sprintf("export const %s = '%s'\n", c.TS, v))
		default:
			require.Contains(t, s, fmt.Sprintf("export const %s = %v\n", c.TS, v))
		}
	}
	for _, e := range schema.Enums {
		quoted := make([]string, 0, len(e.Members))
		names := make([]string, 0, len(e.Members))
		for _, m := range e.Members {
			quoted = append(quoted, "'"+m.Value+"'")
			names = append(names, m.TS)
			require.Contains(t, s, fmt.Sprintf("export const %s: %s = '%s'\n", m.TS, e.TS, m.Value))
		}
		require.Contains(t, s, fmt.Sprintf("export type %s = %s\n", e.TS, strings.Join(quoted, " | ")))
		require.Contains(t, s, fmt.Sprintf("export const %sS: readonly %s[] = [%s]\n",
			strings.ToUpper(e.TS), e.TS, strings.Join(names, ", ")))
	}
	for _, m := range schema.Messages {
		require.Contains(t, s, "export type "+m.Type.Name()+" = {\n")
	}
	for _, r := range schema.Records {
		require.NotContains(t, s, "export type "+r.Name()+" ", "records are Go-only and not rendered")
	}
}

// TestRenderModWire_FieldShapes pins how Go field types and tags map to TypeScript, including the
