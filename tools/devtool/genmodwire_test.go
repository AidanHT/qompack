// gen-mod-wire's own tests, in the shape genmcpdocs_test.go uses: the rows that write set the
// package-level `root` to a sandbox and restore it, because devtool's tests share that variable
// and never run in parallel.
//
// wire.gen.ts is the TypeScript half of internal/modwire. The mod reads the Go binary's stdout
// through those types, so a file that drifted from the Go package would be a wrong specification
// of a live interface, and the CI `docs` job runs --check to make that impossible.

// modWireSandbox points `root` at an empty scratch tree and restores it afterwards.
func modWireSandbox(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	prev := root
	root = dir
	t.Cleanup(func() { root = prev })
	return dir
}

// TestModWireUpToDate is the assertion the CI `docs` job exists to run: both committed generated
// sources are byte-for-byte what the generator produces now.
func TestModWireUpToDate(t *testing.T) {
	for rel, want := range mustRenderModGen(t) {
		got, err := os.ReadFile(filepath.Join(testModuleRoot(t), filepath.FromSlash(rel)))
		require.NoError(t, err, "%s must be committed; run `go run ./tools/devtool gen-mod-wire`", rel)
		require.True(t, bytes.Equal(want, normalizeNewlines(got)),
			"%s is stale; run `go run ./tools/devtool gen-mod-wire`", rel)
	}
}

func mustRenderModGen(t *testing.T) map[string][]byte {
	t.Helper()
	files, err := renderModGenFiles()
	require.NoError(t, err)
	require.Len(t, files, 2)
	return files
}

