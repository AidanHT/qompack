// modWireFile is the generated TypeScript half of internal/modwire, inside modSourceDir.
const modWireFile = "wire.gen.ts"

// taskGenModWire writes the mod's two generated sources under modSourceDir: wire.gen.ts from
// modwire.Schema(), and target.gen.ts as pluginmanifest renders it for the committed target. With
// --check it diffs instead of writing, which is what the CI `docs` job runs.
//
// The Go package is the contract and the TypeScript is derived from it, never the other way round:
// the mod parses the binary's stdout through these types, so a hand-edited copy that drifted would
// be a wrong specification of a live interface.
func taskGenModWire(args []string) error {
	fs := flag.NewFlagSet("gen-mod-wire", flag.ContinueOnError)
	check := fs.Bool("check", false, "diff the generated mod sources against internal/modwire instead of writing them")
	if err := fs.Parse(args); err != nil {
		return errors.Join(errUsage, err)
	}

	files, err := renderModGenFiles()
	if err != nil {
		return fmt.Errorf("gen-mod-wire: %w", err)
	}
	rels := make([]string, 0, len(files))
	for rel := range files {
		rels = append(rels, rel)
	}
	sort.Strings(rels)

	for _, rel := range rels {
		want := files[rel]
		p := filepath.Join(root, filepath.FromSlash(rel))
		if *check {
			got, readErr := os.ReadFile(p)
			if readErr != nil {
				return fmt.Errorf("gen-mod-wire --check: %s is missing; run `devtool gen-mod-wire`", rel)
			}
			if !bytes.Equal(want, normalizeNewlines(got)) {
				return fmt.Errorf("gen-mod-wire --check: %s is stale; run `devtool gen-mod-wire`", rel)
			}
			fmt.Printf("gen-mod-wire: %s is up to date\n", rel)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, want, 0o644); err != nil { // #nosec G306 -- generated tracked source
			return err
		}
		fmt.Printf("gen-mod-wire: wrote %s\n", rel)
	}
	return nil
}

// renderModGenFiles returns both generated sources, keyed by slash path relative to the root.
func renderModGenFiles() (map[string][]byte, error) {
	wire, err := renderModWire()
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		modSourceDir + "/" + modWireFile:                  wire,
		modSourceDir + "/" + pluginmanifest.ModTargetFile: pluginmanifest.ModTargetSource(pluginmanifest.CommittedGOOS),
	}, nil
}

// renderModWire renders wire.gen.ts: the constants, the enums as string unions with a named
// constant per member and a list of all members, then the message shapes, each in Schema() order.
func renderModWire() ([]byte, error) {
	schema := modwire.Schema()
	var b strings.Builder
	b.WriteString("// Code generated by `go run ./tools/devtool gen-mod-wire` from internal/modwire. DO NOT EDIT.\n")
	b.WriteString("// The Go package is the contract; this file is its TypeScript half, and CI fails when\n")
	b.WriteString("// the two drift. Every message carries `v`; a reader ignores fields it does not know.\n")

	for _, c := range schema.Consts {
		lit, err := tsLiteral(c.Value)
		if err != nil {
			return nil, fmt.Errorf("constant %s: %w", c.Go, err)
		}
		fmt.Fprintf(&b, "\n/** %s */\nexport const %s = %s\n", c.Doc, c.TS, lit)
	}

	enumNames := map[reflect.Type]string{}
	for _, e := range schema.Enums {
		enumNames[e.Type] = e.TS
		quoted := make([]string, 0, len(e.Members))
		names := make([]string, 0, len(e.Members))
		for _, m := range e.Members {
			q, err := tsLiteral(m.Value)
			if err != nil {
				return nil, fmt.Errorf("enum %s member %s: %w", e.TS, m.Go, err)
			}
			quoted = append(quoted, q)
			names = append(names, m.TS)
		}
		fmt.Fprintf(&b, "\n/** %s */\nexport type %s = %s\n\n", e.Doc, e.TS, strings.Join(quoted, " | "))
		for i, m := range e.Members {
			fmt.Fprintf(&b, "export const %s: %s = %s\n", m.TS, e.TS, quoted[i])
		}
		fmt.Fprintf(&b, "\n/** Every %s, in declaration order. */\nexport const %sS: readonly %s[] = [%s]\n",
			e.TS, strings.ToUpper(e.TS), e.TS, strings.Join(names, ", "))
	}

	for _, m := range schema.Messages {
		block, err := renderMessage(m, enumNames)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n")
		b.WriteString(block)
	}
	return []byte(b.String()), nil
}

// renderMessage renders one message as a TypeScript object type. An embedded struct's fields are
// flattened in place, as encoding/json flattens them; an omitempty field is optional.
func renderMessage(m modwire.Message, enumNames map[reflect.Type]string) (string, error) {
	if m.Type.Kind() != reflect.Struct {
		return "", fmt.Errorf("message %s is not a struct", m.Type)
	}
	var fields []string
	if err := appendTSFields(&fields, m.Type, enumNames); err != nil {
		return "", fmt.Errorf("message %s: %w", m.Type.Name(), err)
	}
	var b strings.Builder
	if m.Doc != "" {
		fmt.Fprintf(&b, "/** %s */\n", m.Doc)
	}
	fmt.Fprintf(&b, "export type %s = {\n", m.Type.Name())
	for _, f := range fields {
		fmt.Fprintf(&b, "  %s\n", f)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func appendTSFields(out *[]string, t reflect.Type, enumNames map[reflect.Type]string) error {
	for i := range t.NumField() {
		f := t.Field(i)
		if f.Anonymous && f.Type.Kind() == reflect.Struct {
			if err := appendTSFields(out, f.Type, enumNames); err != nil {
				return err
			}
			continue
		}
		if !f.IsExported() {
			continue
		}
		name, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		if name == "-" {
			continue
		}
		if name == "" {
			return fmt.Errorf("field %s has no json name", f.Name)
		}
		ts, err := tsType(f.Type, enumNames)
		if err != nil {
			return fmt.Errorf("field %s: %w", f.Name, err)
		}
		optional := ""
		if strings.Contains(","+opts+",", ",omitempty,") {
			optional = "?"
		}
		*out = append(*out, name+optional+": "+ts)
	}
	return nil
}

// tsType maps the Go field types the contract uses to TypeScript. Anything else is refused, so a
// new field type cannot be rendered as something it is not.
func tsType(t reflect.Type, enumNames map[reflect.Type]string) (string, error) {
	if name, ok := enumNames[t]; ok {
		return name, nil
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return "number", nil
	case reflect.Slice:
		elem, err := tsType(t.Elem(), enumNames)
		if err != nil {
			return "", err
		}
		return elem + "[]", nil
	default:
		return "", fmt.Errorf("no TypeScript rendering for Go type %s", t)
	}
}

// tsLiteral renders a constant's value. Strings are single-quoted, and a value that would need
// escaping is refused rather than escaped: every string in the contract is plain ASCII.
func tsLiteral(v any) (string, error) {
	switch x := v.(type) {
	case string:
		for i := range len(x) {
			if c := x[i]; c < ' ' || c > '~' || c == '\'' || c == '\\' {
				return "", fmt.Errorf("string %q needs escaping", x)
			}
		}
		return "'" + x + "'", nil
	case int:
		return fmt.Sprintf("%d", x), nil
	default:
		return "", fmt.Errorf("no TypeScript literal for %T", v)
	}
}
