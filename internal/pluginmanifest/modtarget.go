package pluginmanifest

import "fmt"

// ModTargetFile is the mod source that differs per target. Every other mod source is the same on
// every target and is embedded as written.
const ModTargetFile = "target.gen.ts"

// ModTargetSource renders target.gen.ts for goos: the target's name and the bundled executable's
// path relative to the plugin root. The committed copy under modsrc/ is the CommittedGOOS
// rendering, written by `go run ./tools/devtool gen-mod-wire`; a bundle for another target carries
// its own rendering in its place.
func ModTargetSource(goos string) []byte {
	return fmt.Appendf(nil, `// Code generated by internal/pluginmanifest (ModTargetSource). DO NOT EDIT.
// Each bundle carries its own target's copy; the copy in the source tree is the %s rendering.

/** The target this copy was rendered for, as Go names it. */
export const TARGET_GOOS = '%s'

/** The bundled executable, relative to the plugin root the host reports. */
export const BINARY_REL_PATH = '%s'
`, CommittedGOOS, goos, BinaryRelPath(goos))
}
